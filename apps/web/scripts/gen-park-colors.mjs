// Generates src/park/colors.css: the Radix Colors scales Park UI is built on, as CSS variables
// switched by `data-theme` (ThemeProvider) or `prefers-color-scheme` before it runs.
// Radix ships `.dark` selectors; PasteWarden themes with `data-theme`, hence this generator.
// Run: node scripts/gen-park-colors.mjs   (the output is committed; @radix-ui/colors is dev-only)
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const radix = createRequire(import.meta.url)('@radix-ui/colors');

// gray = slate (Park UI's natural pairing for a blue-leaning brand navy), accent = teal (the
// wordmark), red / amber for the quarantine / warn verdicts.
const PALETTES = { gray: 'slate', teal: 'teal', red: 'red', amber: 'amber' };

const vars = (dark) =>
  Object.entries(PALETTES)
    .flatMap(([as, name]) => {
      const solid = radix[`${name}${dark ? 'Dark' : ''}`];
      const alpha = radix[`${name}${dark ? 'Dark' : ''}A`];
      return [
        ...Object.values(solid).map((v, i) => `  --${as}-${i + 1}: ${v};`),
        ...Object.values(alpha).map((v, i) => `  --${as}-a${i + 1}: ${v};`),
      ];
    })
    .join('\n');

const css = `/* Generated by scripts/gen-park-colors.mjs from @radix-ui/colors. Do not edit. */
:root,
[data-theme="light"] {
${vars(false)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
${vars(true).replaceAll('\n  ', '\n    ').replace(/^ {2}/, '    ')}
  }
}

[data-theme="dark"] {
${vars(true)}
}
`;

writeFileSync(new URL('../src/park/colors.css', import.meta.url), css);
