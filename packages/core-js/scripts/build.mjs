// Builds @paste-warden/core into dist/ (docs/integrations/wasm.md).
//
// 1. cargo build crates/wasm (wasm-bindgen exports) → wasm-bindgen --target web
//    → wasm-opt -Oz → dist/wasm/
// 2. cargo build crates/wasm --features raw-abi (no wasm-bindgen) → wasm-opt -Oz
//    → wasm2js → dist/wasm2js/ (fallback when WebAssembly is unavailable or
//    blocked by CSP; S2)
// 3. tsc → dist/*.js + .d.ts
//
// Tools: cargo (+ wasm32-unknown-unknown target), wasm-bindgen-cli with the same
// version as the `wasm-bindgen` crate in Cargo.lock, and binaryen's wasm-opt /
// wasm2js from the `binaryen` devDependency (or $WASM_OPT / $WASM2JS).
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(pkg, '../..');
// Intermediate files live under the cargo target dir (ignored by git and Biome).
const build = join(root, 'target', 'core-js');
const dist = join(pkg, 'dist');
const bin = (name) => {
  const env = process.env[name.toUpperCase().replace('-', '_')];
  if (env) return env;
  const local = join(
    pkg,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? `${name}.cmd` : name,
  );
  return existsSync(local) ? local : name;
};

// Features enabled by rustc's wasm32 default target (1.90+). Listed explicitly:
// `--all-features` would let wasm-opt emit tail calls, which wasm2js rejects (S2).
const FEATURES = [
  '--enable-bulk-memory',
  '--enable-bulk-memory-opt',
  '--enable-sign-ext',
  '--enable-nontrapping-float-to-int',
  '--enable-mutable-globals',
  '--enable-reference-types',
  '--enable-multivalue',
];

function run(cmd, args, opts = {}) {
  console.log(`$ ${[cmd, ...args].join(' ')}`);
  execFileSync(cmd, args, {
    stdio: 'inherit',
    cwd: root,
    shell: process.platform === 'win32',
    ...opts,
  });
}

function cargoBuild(features, outName) {
  const args = [
    'build',
    '--locked',
    '-p',
    'paste-warden-wasm',
    '--target',
    'wasm32-unknown-unknown',
    '--profile',
    'release-wasm',
  ];
  if (features) args.push('--no-default-features', '--features', features);
  run('cargo', args);
  const out = join(
    root,
    'target',
    'wasm32-unknown-unknown',
    'release-wasm',
    'paste_warden_wasm.wasm',
  );
  const dest = join(build, outName);
  copyFileSync(out, dest);
  return dest;
}

function checkWasmBindgenVersion() {
  const lock = readFileSync(join(root, 'Cargo.lock'), 'utf8');
  const m = lock.match(/name = "wasm-bindgen"\nversion = "([^"]+)"/);
  const want = m?.[1];
  const have = execFileSync(bin('wasm-bindgen'), ['--version'], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
  })
    .trim()
    .split(' ')[1];
  if (want && have !== want) {
    throw new Error(
      `wasm-bindgen CLI ${have} != crate ${want}; run: cargo install wasm-bindgen-cli --version ${want} --locked`,
    );
  }
}

rmSync(build, { recursive: true, force: true });
rmSync(dist, { recursive: true, force: true });
mkdirSync(build, { recursive: true });
mkdirSync(join(dist, 'wasm'), { recursive: true });
mkdirSync(join(dist, 'wasm2js'), { recursive: true });

// 1. wasm-bindgen build
checkWasmBindgenVersion();
const bindgenWasm = cargoBuild(null, 'bindgen.wasm');
run(bin('wasm-bindgen'), [
  bindgenWasm,
  '--target',
  'web',
  '--out-dir',
  join(build, 'bindgen'),
  '--out-name',
  'paste_warden',
  '--no-typescript',
]);
run(bin('wasm-opt'), [
  ...FEATURES,
  '-Oz',
  '--strip-debug',
  '--strip-producers',
  join(build, 'bindgen', 'paste_warden_bg.wasm'),
  '-o',
  join(dist, 'wasm', 'paste_warden_bg.wasm'),
]);
copyFileSync(join(build, 'bindgen', 'paste_warden.js'), join(dist, 'wasm', 'paste_warden.js'));

// 2. raw ABI → wasm2js
const rawWasm = cargoBuild('raw-abi', 'raw.wasm');
const rawOpt = join(build, 'raw.opt.wasm');
// wasm2js cannot translate the i64 saturating truncations or bulk-memory ops:
// lower them first.
run(bin('wasm-opt'), [
  ...FEATURES,
  '--llvm-nontrapping-fptoint-lowering',
  '--llvm-memory-copy-fill-lowering',
  '-Oz',
  '--strip-debug',
  '--strip-producers',
  rawWasm,
  '-o',
  rawOpt,
]);
const js = join(build, 'paste_warden_raw.js');
run(bin('wasm2js'), [...FEATURES, '-Oz', rawOpt, '-o', js]);
writeFileSync(
  join(dist, 'wasm2js', 'paste_warden_raw.js'),
  `// Generated by binaryen wasm2js from crates/wasm (raw-abi). Do not edit.\n${readFileSync(js, 'utf8')}`,
);

// 3. TypeScript
run(bin('tsc'), ['-p', join(pkg, 'tsconfig.json')]);
console.log('built', dist);
