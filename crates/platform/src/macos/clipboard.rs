//! Raw `NSPasteboard` access (phase-4.md §4.9.1, S4). Every function here
//! runs on the `pw-clip` thread inside the caller's `autoreleasepool`; other
//! threads go through [`super::monitor::ClipboardHandle`].
//!
//! Nothing in this file formats clipboard content into errors or logs (P3).
//! Text we copy out lives in [`Zeroizing`] buffers; the `NSData` / `NSString`
//! objects themselves belong to AppKit and cannot be wiped by us.

use objc2::msg_send;
use objc2::rc::{Retained, autoreleasepool};
use objc2_app_kit::{NSPasteboard, NSPasteboardAccessBehavior, NSPasteboardTypeString};
use objc2_foundation::{NSData, NSString};
use zeroize::Zeroizing;

use crate::clipboard::{
    ClipEvent, ClipText, ClipboardFlags, EmptyReason, MAX_ANALYZED_CHARS, SOURCE_URL_MAX_BYTES,
    accept_source_url, decode_format_text,
};

/// How often `pw-clip` reads `changeCount` (S4: 27 µs per idle poll).
pub const POLL_INTERVAL_MS: u64 = 250;
/// nspasteboard.org markers set by password managers: when any is present the
/// text is not read at all (S4).
pub const CONCEALED_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];
/// Plain UTF-8 text (`NSPasteboardTypeString`).
pub const TEXT_TYPE: &str = "public.utf8-plain-text";
/// Page URL that Chromium browsers attach to copies (S4 finding 1).
pub const SOURCE_URL_TYPE: &str = "org.chromium.source-url";
/// Types saved before a masked paste and put back afterwards (§5.3).
pub const RESTORE_TYPES: [&str; 3] = [TEXT_TYPE, "public.rtf", "public.html"];
/// UTF-8 bytes scanned for the analyzed prefix: every char is at most 4
/// bytes, so this always covers [`MAX_ANALYZED_CHARS`] chars.
pub const MAX_TEXT_SCAN_BYTES: usize = MAX_ANALYZED_CHARS * 4;

/// A pasteboard operation failed. Carries no clipboard content.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ClipError {
    /// The monitor thread did not answer in time (or is gone).
    Busy,
    /// AppKit refused the write (`setString:forType:` returned NO).
    WriteFailed,
}

/// Which pasteboard the monitor watches. Tests use a private named one so
/// they never touch the user's clipboard.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub enum PasteboardSource {
    /// `NSPasteboard.generalPasteboard` (the user's clipboard).
    #[default]
    General,
    /// `NSPasteboard.pasteboardWithName:`.
    Named(String),
}

/// `NSPasteboard.accessBehavior` (macOS 15.4+ pasteboard privacy). Reading
/// the general pasteboard's content programmatically may show an alert when
/// this is `Default` or `Ask`; `changeCount` and `types` never do.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PasteboardAccess {
    Default,
    Ask,
    AlwaysAllow,
    AlwaysDeny,
    /// A value this build does not know.
    Other(isize),
}

impl From<NSPasteboardAccessBehavior> for PasteboardAccess {
    fn from(b: NSPasteboardAccessBehavior) -> Self {
        match b {
            NSPasteboardAccessBehavior::Default => PasteboardAccess::Default,
            NSPasteboardAccessBehavior::Ask => PasteboardAccess::Ask,
            NSPasteboardAccessBehavior::AlwaysAllow => PasteboardAccess::AlwaysAllow,
            NSPasteboardAccessBehavior::AlwaysDeny => PasteboardAccess::AlwaysDeny,
            other => PasteboardAccess::Other(other.0),
        }
    }
}

/// Decides from the type list alone whether the text may be read. A
/// concealed / transient / auto-generated marker maps to
/// [`ClipboardFlags::exclude_monitor`].
pub fn flags_from_types<S: AsRef<str>>(types: impl IntoIterator<Item = S>) -> ClipboardFlags {
    let mut flags = ClipboardFlags::default();
    for t in types {
        let t = t.as_ref();
        if t == TEXT_TYPE {
            flags.has_text = true;
        } else if CONCEALED_TYPES.contains(&t) {
            flags.exclude_monitor = true;
        }
    }
    flags
}

/// Decodes at most [`MAX_ANALYZED_CHARS`] chars of UTF-8 (invalid sequences
/// become U+FFFD) straight into a zeroized buffer. Only the first
/// [`MAX_TEXT_SCAN_BYTES`] bytes are looked at. Returns the text and whether
/// it was cut.
pub fn decode_utf8_prefix(bytes: &[u8]) -> (Zeroizing<String>, bool) {
    let scan = &bytes[..bytes.len().min(MAX_TEXT_SCAN_BYTES)];
    let mut out = Zeroizing::new(String::with_capacity(scan.len().min(MAX_ANALYZED_CHARS)));
    let mut chars = 0usize;
    for chunk in scan.utf8_chunks() {
        let pieces = chunk
            .valid()
            .chars()
            .chain((!chunk.invalid().is_empty()).then_some(char::REPLACEMENT_CHARACTER));
        for c in pieces {
            if chars == MAX_ANALYZED_CHARS {
                return (out, true);
            }
            out.push(c);
            chars += 1;
        }
    }
    // Fewer than MAX chars in the scanned window means the window was the
    // whole input (see MAX_TEXT_SCAN_BYTES), except for a char cut at the
    // window edge, which only happens when the input is longer.
    (out, bytes.len() > scan.len())
}

/// The page URL from `org.chromium.source-url` bytes, when it is an http(s)
/// URL within [`SOURCE_URL_MAX_BYTES`]. Longer payloads are dropped unread.
pub fn source_url_from_bytes(bytes: &[u8]) -> Option<String> {
    // Allow a few trailing NULs; anything else past the limit is too long.
    let trimmed_len = bytes.iter().rposition(|&b| b != 0).map_or(0, |i| i + 1);
    if trimmed_len == 0 || trimmed_len > SOURCE_URL_MAX_BYTES {
        return None;
    }
    decode_format_text(&bytes[..trimmed_len])
        .as_deref()
        .and_then(accept_source_url)
}

/// Text saved before a masked paste, to put back afterwards.
pub struct Snapshot {
    items: Vec<(&'static str, Zeroizing<Vec<u8>>)>,
}

impl std::fmt::Debug for Snapshot {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Snapshot")
            .field("types", &self.items.len())
            .finish()
    }
}

/// `changeCount` as the shared `u32` sequence number (wrapping).
pub fn sequence_from_count(count: isize) -> u32 {
    count as u32
}

/// Releases a named pasteboard's resources in the pasteboard server
/// (`releaseGlobally`). For tests and private pasteboards; never call it on
/// the general pasteboard's name.
pub fn release_named_pasteboard(name: &str) {
    autoreleasepool(|_| {
        let pb = NSPasteboard::pasteboardWithName(&ns(name));
        // SAFETY: `releaseGlobally` takes no arguments and returns void; `pb`
        // is a valid pasteboard object.
        let () = unsafe { msg_send![&*pb, releaseGlobally] };
    });
}

/// One pasteboard, owned by the monitor thread (`NSPasteboard` is not `Send`).
pub struct Pasteboard {
    pb: Retained<NSPasteboard>,
}

fn ns(s: &str) -> Retained<NSString> {
    NSString::from_str(s)
}

impl Pasteboard {
    pub fn open(source: &PasteboardSource) -> Pasteboard {
        let pb = match source {
            PasteboardSource::General => NSPasteboard::generalPasteboard(),
            PasteboardSource::Named(name) => NSPasteboard::pasteboardWithName(&ns(name)),
        };
        Pasteboard { pb }
    }

    /// `changeCount`, as a sequence number. Never shows a privacy alert.
    pub fn sequence(&self) -> u32 {
        sequence_from_count(self.pb.changeCount())
    }

    pub fn access(&self) -> PasteboardAccess {
        self.pb.accessBehavior().into()
    }

    fn flags(&self) -> ClipboardFlags {
        match self.pb.types() {
            Some(types) => flags_from_types(types.iter().map(|t| t.to_string())),
            None => ClipboardFlags::default(),
        }
    }

    fn data(&self, ty: &str) -> Option<Retained<NSData>> {
        self.pb.dataForType(&ns(ty))
    }

    fn source_url(&self) -> Option<String> {
        let data = self.data(SOURCE_URL_TYPE)?;
        if data.len() > SOURCE_URL_MAX_BYTES + 4 {
            return None;
        }
        // SAFETY: `data` is an immutable NSData we hold a reference to and
        // nothing mutates it while the slice is borrowed.
        source_url_from_bytes(unsafe { data.as_bytes_unchecked() })
    }

    /// Reads one change: types first, text only when no marker is present.
    ///
    /// `ours(sequence)` says the pasteboard holds our own write; markers are
    /// then ignored (we never write them, but a restore could carry them).
    pub fn read_change(&self, ours: impl FnOnce(u32) -> bool) -> ClipEvent {
        let sequence = self.sequence();
        let mut flags = self.flags();
        let self_write = ours(sequence);
        if self_write {
            flags.exclude_monitor = false;
        }
        if let Some(reason) = flags.empty_reason() {
            return ClipEvent::Empty { sequence, reason };
        }
        let Some(data) = self.data(TEXT_TYPE) else {
            // Declared but not delivered: access denied, or the owner failed.
            return ClipEvent::Empty {
                sequence,
                reason: EmptyReason::Unreadable,
            };
        };
        // SAFETY: as in `source_url`.
        let (text, truncated) = decode_utf8_prefix(unsafe { data.as_bytes_unchecked() });
        drop(data);
        ClipEvent::Text(ClipText {
            sequence,
            text,
            truncated,
            source_url: self.source_url(),
            owner_process: None,
            self_write,
        })
    }

    /// The complete text (only used when quarantining a cut text).
    pub fn read_full(&self) -> Option<Zeroizing<String>> {
        let data = self.data(TEXT_TYPE)?;
        // SAFETY: as in `source_url`.
        let bytes = unsafe { data.as_bytes_unchecked() };
        let mut out = Zeroizing::new(String::with_capacity(bytes.len()));
        for chunk in bytes.utf8_chunks() {
            out.push_str(chunk.valid());
            if !chunk.invalid().is_empty() {
                out.push(char::REPLACEMENT_CHARACTER);
            }
        }
        Some(out)
    }

    /// `clearContents()` then plain text only. Returns the new sequence.
    pub fn write_text(&self, text: &str) -> Result<u32, ClipError> {
        self.pb.clearContents();
        // SAFETY: reading an AppKit constant.
        let ty = unsafe { NSPasteboardTypeString };
        // The NSString copy belongs to AppKit and cannot be zeroized.
        if !self.pb.setString_forType(&ns(text), ty) {
            return Err(ClipError::WriteFailed);
        }
        Ok(self.sequence())
    }

    /// Empties the pasteboard (quarantine). Returns the new sequence.
    pub fn clear(&self) -> Result<u32, ClipError> {
        self.pb.clearContents();
        Ok(self.sequence())
    }

    /// Saves [`RESTORE_TYPES`].
    pub fn snapshot(&self) -> Snapshot {
        let items = RESTORE_TYPES
            .iter()
            .filter_map(|&ty| self.data(ty).map(|d| (ty, Zeroizing::new(d.to_vec()))))
            .collect();
        Snapshot { items }
    }

    /// Puts a [`Snapshot`] back. Returns the new sequence.
    pub fn restore(&self, snap: &Snapshot) -> Result<u32, ClipError> {
        self.pb.clearContents();
        for (ty, bytes) in &snap.items {
            if !self
                .pb
                .setData_forType(Some(&NSData::with_bytes(bytes)), &ns(ty))
            {
                return Err(ClipError::WriteFailed);
            }
        }
        Ok(self.sequence())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn markers_decide_before_reading() {
        let f = flags_from_types([TEXT_TYPE, "public.html"]);
        assert!(f.has_text && !f.exclude_monitor);
        assert_eq!(f.empty_reason(), None);
        for marker in CONCEALED_TYPES {
            let f = flags_from_types([TEXT_TYPE, marker]);
            assert_eq!(f.empty_reason(), Some(EmptyReason::Excluded), "{marker}");
        }
        assert_eq!(
            flags_from_types(["public.png"]).empty_reason(),
            Some(EmptyReason::NoText)
        );
        assert_eq!(
            flags_from_types(Vec::<String>::new()).empty_reason(),
            Some(EmptyReason::NoText)
        );
    }

    #[test]
    fn utf8_prefix_limits_and_replacement() {
        let (t, cut) = decode_utf8_prefix("ab😀".as_bytes());
        assert_eq!(t.as_str(), "ab😀");
        assert!(!cut);

        let (t, cut) = decode_utf8_prefix(b"a\xffb");
        assert_eq!(t.as_str(), "a\u{FFFD}b");
        assert!(!cut);

        let long = vec![b'a'; MAX_ANALYZED_CHARS + 1];
        let (t, cut) = decode_utf8_prefix(&long);
        assert_eq!(t.chars().count(), MAX_ANALYZED_CHARS);
        assert!(cut);

        let exact = vec![b'a'; MAX_ANALYZED_CHARS];
        let (t, cut) = decode_utf8_prefix(&exact);
        assert_eq!(t.chars().count(), MAX_ANALYZED_CHARS);
        assert!(!cut);

        // Four-byte chars filling the scan window exactly, then one more.
        let mut wide = "😀".repeat(MAX_ANALYZED_CHARS).into_bytes();
        let (t, cut) = decode_utf8_prefix(&wide);
        assert_eq!(t.chars().count(), MAX_ANALYZED_CHARS);
        assert!(!cut);
        wide.push(b'x');
        let (_, cut) = decode_utf8_prefix(&wide);
        assert!(cut);

        // Invalid bytes only: each becomes one U+FFFD and the limit holds.
        let junk = vec![0xffu8; MAX_TEXT_SCAN_BYTES + 10];
        let (t, cut) = decode_utf8_prefix(&junk);
        assert_eq!(t.chars().count(), MAX_ANALYZED_CHARS);
        assert!(cut);

        let (t, cut) = decode_utf8_prefix(b"");
        assert!(t.is_empty() && !cut);
    }

    #[test]
    fn source_url_is_capped_and_checked() {
        assert_eq!(
            source_url_from_bytes(b"https://example.invalid/page").as_deref(),
            Some("https://example.invalid/page")
        );
        assert_eq!(
            source_url_from_bytes(b"https://example.invalid/page\0").as_deref(),
            Some("https://example.invalid/page")
        );
        assert_eq!(source_url_from_bytes(b"file:///etc/hosts"), None);
        assert_eq!(source_url_from_bytes(b""), None);
        assert_eq!(source_url_from_bytes(b"\0\0"), None);
        let long = format!(
            "https://example.invalid/{}",
            "a".repeat(SOURCE_URL_MAX_BYTES)
        );
        assert_eq!(source_url_from_bytes(long.as_bytes()), None);
    }

    #[test]
    fn sequence_wraps() {
        assert_eq!(sequence_from_count(5), 5);
        assert_eq!(sequence_from_count(u32::MAX as isize + 2), 1);
        assert_eq!(sequence_from_count(-1), u32::MAX);
    }

    #[test]
    fn snapshot_debug_hides_content() {
        let s = Snapshot {
            items: vec![(TEXT_TYPE, Zeroizing::new(b"hidden-words".to_vec()))],
        };
        let d = format!("{s:?}");
        assert!(!d.contains("hidden"));
    }
}
