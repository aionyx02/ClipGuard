// 從 .resx 產生強型別的存取類別（取代 Visual Studio 的 ResXFileCodeGenerator，dotnet CLI 沒有它）。
//
//   node tools/gen-resx-accessors.mjs          重新產生
//   node tools/gen-resx-accessors.mjs --check  只檢查產生的檔案是不是最新的（不一致時 exit 1）
//
// 規則：
// - 來源是中性語系（英文）的 .resx；翻譯檔（*.zh-TW.resx）的 key 要跟它一樣，由 C# 測試 LocalizationTests 檢查。
// - 沒有 {0} 的字串產生屬性；有 {0}…{n} 的產生方法，參數個數跟最大的索引一致，呼叫端少給參數時編譯就會失敗。
// - key 不是合法 C# 識別字（例如 RuleLabel_sk-api-key）時不產生成員，用 Lookup(key) 取。
// - 每次都依目前的 CurrentUICulture 取字串，不快取，所以測試可以在同一個行程裡切換語系。
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const TARGETS = [
  {
    resx: 'src/ClipGuard.App/Resources/Strings.resx',
    out: 'src/ClipGuard.App/Resources/Strings.g.cs',
    namespace: 'ClipGuard.App',
    className: 'Strings',
    baseName: 'ClipGuard.App.Resources.Strings',
  },
  {
    resx: 'src/ClipGuard.Core/Resources/CoreStrings.resx',
    out: 'src/ClipGuard.Core/Resources/CoreStrings.g.cs',
    namespace: 'ClipGuard.Core',
    className: 'CoreStrings',
    baseName: 'ClipGuard.Core.Resources.CoreStrings',
  },
];

const unescapeXml = (s) =>
  s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');

export function readResx(path) {
  const xml = readFileSync(path, 'utf8');
  const entries = [];
  for (const m of xml.matchAll(/<data\s+name="([^"]+)"[^>]*>\s*<value>([\s\S]*?)<\/value>/g)) {
    entries.push({ key: unescapeXml(m[1]), value: unescapeXml(m[2]) });
  }
  return entries;
}

// {0}、{1:0} 這類格式項目的索引；{{ 和 }} 是跳脫的大括號。
export function placeholderCount(value) {
  let max = -1;
  for (const m of value.replace(/\{\{|\}\}/g, '').matchAll(/\{(\d+)(?:[,:][^}]*)?\}/g)) max = Math.max(max, Number(m[1]));
  return max + 1;
}

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
const xmlDoc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function generate(t) {
  const entries = readResx(join(root, t.resx));
  const members = entries
    .filter((e) => IDENTIFIER.test(e.key))
    .map(({ key, value }) => {
      const n = placeholderCount(value);
      const doc = `    /// <summary>${xmlDoc(value)}</summary>`;
      if (n === 0) return `${doc}\n    internal static string ${key} => Get(nameof(${key}));`;
      const params = Array.from({ length: n }, (_, i) => `object? arg${i}`).join(', ');
      const args = Array.from({ length: n }, (_, i) => `arg${i}`).join(', ');
      return `${doc}\n    internal static string ${key}(${params}) => Format(nameof(${key}), ${args});`;
    });

  return `// <auto-generated>
// 由 tools/gen-resx-accessors.mjs 從 ${t.resx.split('/').pop()} 產生，不要手改：改 .resx 後重新執行該腳本。
// </auto-generated>
#nullable enable
using System.Globalization;
using System.Resources;

namespace ${t.namespace};

internal static class ${t.className}
{
    internal static ResourceManager ResourceManager { get; } =
        new("${t.baseName}", typeof(${t.className}).Assembly);

    /// <summary>依目前的 UI 語系取字串；key 不存在時回傳 null。</summary>
    internal static string? Lookup(string key) => ResourceManager.GetString(key, CultureInfo.CurrentUICulture);

    private static string Get(string key) => Lookup(key) ?? key;

    private static string Format(string key, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), args);

${members.join('\n\n')}
}
`.replace(/\r?\n/g, '\r\n');
}

const check = process.argv.includes('--check');
let stale = false;
for (const t of TARGETS) {
  const code = generate(t);
  const path = join(root, t.out);
  if (check) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* 沒有檔案就算過期 */ }
    if (current.replace(/\r\n/g, '\n') !== code.replace(/\r\n/g, '\n')) {
      console.error(`${t.out} 不是最新的，請執行 node tools/gen-resx-accessors.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(path, code);
    console.log(`${t.out}`);
  }
}
if (stale) process.exit(1);
